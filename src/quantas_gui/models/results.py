"""Passive contracts used by the Results Explorer.

These dataclasses intentionally contain only lightweight, JSON-compatible
metadata. Numerical result arrays, Quantas result envelopes, report tables,
and plot collections remain server-side and are reopened on demand.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from typing import Any


@dataclass(frozen=True, slots=True)
class ResultReference:
    """Opaque reference to one server-side native result.

    Parameters
    ----------
    workspace_id
        Isolated workspace identifier generated by the GUI.
    result_id
        Opaque identifier mapped to the native HDF5 file by the result store.
    filename
        Sanitized display name of the uploaded file.
    size_bytes
        Physical upload size in bytes.
    """

    workspace_id: str
    result_id: str
    filename: str
    size_bytes: int

    def as_dict(self) -> dict[str, Any]:
        """Return a JSON-compatible representation."""
        return asdict(self)

    @classmethod
    def from_dict(cls, values: dict[str, Any]) -> ResultReference:
        """Restore a reference from browser-session data."""
        return cls(
            workspace_id=str(values["workspace_id"]),
            result_id=str(values["result_id"]),
            filename=str(values["filename"]),
            size_bytes=int(values["size_bytes"]),
        )


@dataclass(frozen=True, slots=True)
class ResultSummary:
    """Lightweight result identity displayed in the Explorer header."""

    module: str
    module_title: str
    method: str | None
    program: str | None
    quantas_version: str | None
    schema_version: str | None
    created_at: str | None
    created_by: str | None
    capabilities: tuple[str, ...] = ()
    warning_count: int = 0
    event_count: int = 0
    result_keys: tuple[str, ...] = ()
    archive: bool = False

    def as_dict(self) -> dict[str, Any]:
        """Return a JSON-compatible representation."""
        values = asdict(self)
        values["capabilities"] = list(self.capabilities)
        values["result_keys"] = list(self.result_keys)
        return values

    @classmethod
    def from_dict(cls, values: dict[str, Any]) -> ResultSummary:
        """Restore a summary from browser-session data."""
        return cls(
            module=str(values["module"]),
            module_title=str(values["module_title"]),
            method=_optional_text(values.get("method")),
            program=_optional_text(values.get("program")),
            quantas_version=_optional_text(values.get("quantas_version")),
            schema_version=_optional_text(values.get("schema_version")),
            created_at=_optional_text(values.get("created_at")),
            created_by=_optional_text(values.get("created_by")),
            capabilities=tuple(str(item) for item in values.get("capabilities", ())),
            warning_count=int(values.get("warning_count", 0)),
            event_count=int(values.get("event_count", 0)),
            result_keys=tuple(str(item) for item in values.get("result_keys", ())),
            archive=bool(values.get("archive", False)),
        )


@dataclass(frozen=True, slots=True)
class InventoryItem:
    """Compact description of one persisted or restored value."""

    key: str
    value_type: str
    shape: tuple[int, ...] | None = None
    dtype: str | None = None
    summary: str | None = None

    def as_dict(self) -> dict[str, Any]:
        """Return a JSON-compatible representation."""
        values = asdict(self)
        values["shape"] = None if self.shape is None else list(self.shape)
        return values


@dataclass(frozen=True, slots=True)
class EventView:
    """Serializable event displayed by the message timeline."""

    level: str
    message: str
    timestamp: str | None = None
    progress: float | None = None
    data: dict[str, Any] = field(default_factory=dict)

    def as_dict(self) -> dict[str, Any]:
        """Return a JSON-compatible representation."""
        return asdict(self)


@dataclass(frozen=True, slots=True)
class ResultOverview:
    """Lightweight inspection snapshot used by non-plot Explorer sections."""

    summary: ResultSummary
    metadata: dict[str, Any]
    input_data: dict[str, Any]
    options: dict[str, Any]
    inventory: tuple[InventoryItem, ...]
    warnings: tuple[str, ...]
    events: tuple[EventView, ...]


@dataclass(slots=True)
class TableData:
    """GUI-owned structural equivalent of a neutral Quantas report table."""

    title: str
    columns: list[str]
    rows: list[list[Any]]
    metadata: dict[str, Any] = field(default_factory=dict)


def _optional_text(value: Any) -> str | None:
    """Return normalized optional text."""
    if value is None:
        return None
    text = str(value).strip()
    return text or None
